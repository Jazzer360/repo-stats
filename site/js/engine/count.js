// Content analysis: counts lines/words and refines path-based classification
// (generated headers, minified files, shebangs, binary content).

import { LANGUAGES, SHEBANG } from './languages.js';

const NO_SINGLE_QUOTE_STRINGS = new Set(['Rust', 'Lisp', 'Clojure', 'Haskell', 'OCaml', 'Elm', 'Visual Basic', 'F#', 'Erlang', 'Vim Script', 'Batchfile', 'Fortran', 'VHDL', 'Assembly', 'Markdown', 'HTML', 'XML', 'XAML', 'Templates', 'TeX', 'MATLAB', 'Power Query']);
const BACKTICK_STRINGS = new Set(['JavaScript', 'TypeScript', 'Vue', 'Svelte', 'Astro', 'Go', 'Kotlin']);
const HASH_NOT_COMMENT_START = new Set(['Shell']); // "$#" is not a comment; handled by requiring whitespace/start before '#'

// Strong markers only: a marker must clearly claim the *file* is generated.
const GENERATED_MARKERS_CS = /@generated\b|\bDO NOT (EDIT|MODIFY)\b|\bCode generated\b.*\bDO NOT EDIT\b/;
const GENERATED_MARKERS = /\b(this|the) (file|code|module|class) (is|was|has been) (auto(matically)?[- ]?)?generated\b|\bauto-?generated (by|from|with|using|file)\b|\bautomatically generated (by|from|with|using)\b|^\W{0,6}(auto-?)?generated (by|with|from|using) \S|\bgenerated by the protocol buffer compiler\b|\bautogenerated by thrift\b/im;
const VS_DESIGNER = /<auto-generated>|This code was generated by a tool/i;

export function isProbablyBinary(text) {
  const n = Math.min(text.length, 8000);
  for (let i = 0; i < n; i++) if (text.charCodeAt(i) === 0) return true;
  return false;
}

export function shebangLanguage(text) {
  if (!text.startsWith('#!')) return null;
  const first = text.slice(0, text.indexOf('\n') >>> 0 || 200);
  for (const [re, lang] of SHEBANG) if (re.test(first)) return lang;
  return null;
}

export function hasGeneratedMarker(text) {
  const head = text.slice(0, 1500);
  // Only look at the first few lines so a sentence deep inside a file doesn't trigger it.
  const lines = head.split('\n').slice(0, 12).join('\n');
  return GENERATED_MARKERS_CS.test(lines) || GENERATED_MARKERS.test(lines) || VS_DESIGNER.test(lines);
}

function isMinified(text, lines, lang) {
  if (!/^(JavaScript|TypeScript|CSS|SCSS|Less|HTML|SVG)$/.test(lang || '')) return false;
  if (text.length < 4000) return false;
  const avg = text.length / Math.max(1, lines);
  if (avg > 300) return true;
  // any single line over 5000 chars in a script/style file
  let start = 0;
  while (start < text.length) {
    let end = text.indexOf('\n', start);
    if (end < 0) end = text.length;
    if (end - start > 5000) return true;
    start = end + 1;
  }
  return false;
}

/** Split into physical lines (handles \r\n, \r). Trailing newline does not create an extra line. */
export function splitLines(text) {
  const lines = text.split(/\r\n|\r|\n/);
  if (lines.length && lines[lines.length - 1] === '') lines.pop();
  return lines;
}

/**
 * Count code / comment / blank lines with a small lexer that understands line
 * comments, (optionally nested) block comments and string literals well enough
 * to not mistake "http://x" inside a string for a comment.
 */
export function countCode(lines, lang) {
  const info = LANGUAGES[lang];
  const style = info ? info.comments : { line: [], block: [] };
  const lineTok = style.line;
  const blocks = style.block;
  const quotes = NO_SINGLE_QUOTE_STRINGS.has(lang) ? ['"'] : ['"', "'"];
  if (BACKTICK_STRINGS.has(lang)) quotes.push('`');
  let code = 0, comment = 0, blank = 0, todos = 0;
  let inBlock = null; // closing token
  let depth = 0;
  let inString = null; // only for multi-line backtick strings

  for (const raw of lines) {
    const line = raw;
    const trimmed = line.trim();
    if (!trimmed && !inString) { blank++; continue; }
    let hasCode = false, hasComment = false;
    let i = 0;
    const n = line.length;
    if (inString) hasCode = true;
    while (i < n) {
      if (inString) {
        const ch = line[i];
        if (ch === '\\') { i += 2; continue; }
        if (ch === inString) { inString = null; }
        i++; continue;
      }
      if (inBlock) {
        hasComment = true;
        if (line.startsWith(inBlock, i)) { i += inBlock.length; if (--depth <= 0) { inBlock = null; depth = 0; } continue; }
        if (style.nested) {
          const opener = blocks.find(b => b[1] === inBlock)[0];
          if (line.startsWith(opener, i)) { depth++; i += opener.length; continue; }
        }
        i++; continue;
      }
      const ch = line[i];
      if (ch === ' ' || ch === '\t') { i++; continue; }
      // block comment start
      let matched = false;
      for (const [open, close] of blocks) {
        if (line.startsWith(open, i)) {
          if (style.blockAtLineStart && line.slice(0, i).trim() !== '') continue;
          inBlock = close; depth = 1; hasComment = true; i += open.length; matched = true; break;
        }
      }
      if (matched) continue;
      // line comment
      for (const tok of lineTok) {
        if (line.startsWith(tok, i)) {
          if (tok === '#' && HASH_NOT_COMMENT_START.has(lang) && i > 0 && !/\s/.test(line[i - 1])) continue;
          hasComment = true; matched = true; break;
        }
      }
      if (matched) break;
      // strings
      if (quotes.includes(ch)) {
        hasCode = true;
        let j = i + 1;
        let closed = false;
        while (j < n) {
          if (line[j] === '\\') { j += 2; continue; }
          if (line[j] === ch) { closed = true; break; }
          j++;
        }
        if (!closed && ch === '`') inString = '`';
        i = closed ? j + 1 : n;
        continue;
      }
      hasCode = true;
      i++;
    }
    if (hasComment && /\b(TODO|FIXME|HACK|XXX)\b/.test(line)) todos++;
    if (hasCode) code++;
    else if (hasComment) comment++;
    else blank++;
  }
  return { code, comment, blank, todos };
}

/** A word is any whitespace-separated token containing at least one letter. */
export function countWords(text) {
  let words = 0;
  const re = /\S+/g;
  let m;
  while ((m = re.exec(text))) if (/\p{L}/u.test(m[0])) words++;
  return words;
}

/** Prose analysis for Markdown-like docs: words excluding code samples, URLs and markup. */
export function analyzeProse(text, lang) {
  let body = text;
  const extra = {};
  if (lang === 'Markdown' || lang === 'reStructuredText' || lang === 'AsciiDoc' || lang === 'Org' || lang === 'Text') {
    // YAML front matter
    body = body.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, '');
    let samples = 0;
    // fenced code blocks (``` ~~~), asciidoc ---- blocks
    body = body.replace(/^(\s*)(`{3,}|~{3,})[^\n]*\n([\s\S]*?)^\s*\2[`~]*\s*$/gm, (_, _i, _f, inner) => { samples += splitLines(inner).length; return '\n'; });
    if (lang === 'reStructuredText') body = body.replace(/::\s*\n((?:[ \t]+.*\n|\s*\n)+)/g, (_, inner) => { samples += splitLines(inner).filter(l => l.trim()).length; return '\n'; });
    if (lang === 'Org') body = body.replace(/#\+BEGIN_SRC[\s\S]*?#\+END_SRC/gi, m => { samples += splitLines(m).length - 2; return '\n'; });
    extra.samples = samples;
    extra.headings = (body.match(/^#{1,6}\s+\S/gm) || []).length + (body.match(/^[^\n]+\n(=+|-+)\s*$/gm) || []).length;
    extra.links = (body.match(/\]\([^)]+\)|<https?:\/\/[^>]+>|https?:\/\/\S+/g) || []).length;
    extra.images = (body.match(/!\[[^\]]*\]\(|<img\b/gi) || []).length;
    body = body
      .replace(/<!--[\s\S]*?-->/g, ' ')
      .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
      .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
      .replace(/^\s*\[[^\]]+\]:\s*\S+.*$/gm, ' ')
      .replace(/<\/?[a-zA-Z][^>]*>/g, ' ')
      .replace(/https?:\/\/\S+/g, ' ');
  } else if (lang === 'TeX') {
    body = body.replace(/(^|[^\\])%.*$/gm, '$1').replace(/\\begin\{(verbatim|lstlisting|minted)\}[\s\S]*?\\end\{\1\}/g, ' ').replace(/\\[a-zA-Z@]+\*?/g, ' ');
  }
  extra.words = countWords(body);
  return extra;
}

function analyzeNotebook(text) {
  try {
    const nb = JSON.parse(text);
    const lang = (nb.metadata?.kernelspec?.language || nb.metadata?.language_info?.name || 'python').toLowerCase();
    const langName = { python: 'Python', r: 'R', julia: 'Julia', scala: 'Scala', 'c#': 'C#', javascript: 'JavaScript', typescript: 'TypeScript' }[lang] || 'Python';
    let code = 0, comment = 0, blank = 0, words = 0, cells = 0, outputs = 0;
    for (const cell of nb.cells || nb.worksheets?.[0]?.cells || []) {
      cells++;
      const src = Array.isArray(cell.source) ? cell.source.join('') : (cell.source || cell.input || '');
      const s = Array.isArray(src) ? src.join('') : src;
      if (cell.cell_type === 'code') {
        const r = countCode(splitLines(s), langName);
        code += r.code; comment += r.comment; blank += r.blank;
        outputs += (cell.outputs || []).length;
      } else if (cell.cell_type === 'markdown') words += analyzeProse(s, 'Markdown').words;
    }
    return { code, comment, blank, words, cells, outputs, nbLang: langName };
  } catch {
    return null;
  }
}

/**
 * Refine a path classification with the file's text and compute counts.
 * rec: { cat, kind, lang } from classifyPath. Returns a new record with counts.
 * Fields: n=lines, cd=code, cm=comment, bl=blank, w=words, t=todos, x=extra
 */
export function analyzeContent(rec, text) {
  const out = { ...rec };
  if (text == null) return out;
  if (isProbablyBinary(text)) { out.cat = 'assets'; out.kind = 'binary'; return out; }
  const lines = splitLines(text);
  out.n = lines.length;

  if (!out.lang) {
    const sb = shebangLanguage(text);
    if (sb) { out.lang = sb; out.cat = 'code'; out.kind = /(^|\/)(tests?)\//.test(rec.path || '') ? 'test' : 'script'; }
  }
  if (out.lang === 'Objective-C' && /^\s*(function\b|%|classdef\b)/m.test(text.slice(0, 2000)) && !/@(interface|implementation|import)|#import/.test(text)) out.lang = 'MATLAB';

  if (out.cat !== 'generated' && out.cat !== 'vendored' && out.kind !== 'vcs' && hasGeneratedMarker(text)) {
    out.cat = 'generated'; out.kind = 'codegen';
  } else if (out.cat === 'code' && isMinified(text, lines.length, out.lang)) {
    out.cat = 'generated'; out.kind = 'minified';
  }

  if (out.kind === 'notebook') {
    const nb = analyzeNotebook(text);
    if (nb) {
      out.cd = nb.code; out.cm = nb.comment; out.bl = nb.blank; out.w = nb.words;
      out.x = { cells: nb.cells, outputs: nb.outputs, nbLang: nb.nbLang };
    }
    return out;
  }

  if (out.cat === 'docs') {
    const p = analyzeProse(text, out.lang);
    out.w = p.words;
    const { words, ...x } = p;
    if (Object.keys(x).length) out.x = x;
    out.bl = lines.filter(l => !l.trim()).length;
    return out;
  }

  if (out.cat === 'code' || out.cat === 'config' || out.cat === 'generated') {
    const r = countCode(lines, out.lang);
    out.cd = r.code; out.cm = r.comment; out.bl = r.blank;
    if (r.todos) out.t = r.todos;
    return out;
  }

  // data / other: lines + blank only
  out.bl = lines.filter(l => !l.trim()).length;
  if (out.cat === 'other') out.w = countWords(text);
  return out;
}
